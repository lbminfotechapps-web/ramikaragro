class SelectedCropDetail {
  final String cropId;
  final String cropName;
  final DateTime date;
  final String acre;
  final String irrigationId;
  final String irrigationName;

  SelectedCropDetail({
    required this.cropId,
    required this.cropName,
    required this.date,
    required this.acre,
    required this.irrigationId,
    required this.irrigationName,
  });
}