class Organization {
  final String organizationName;
  final String organizationAddress;
  final String organizationEmail;
  final String organizationContact;
  final String organizationLat;
  final String organizationLang;
  final String organizationHome;

  final String organizationAboutUs;
  final String organizationContactUs;
  final String organizationUserGuideLine;

  const Organization({
    required this.organizationName,
    required this.organizationAddress,
    required this.organizationEmail,
    required this.organizationContact,
    required this.organizationLat,
    required this.organizationLang,
    required this.organizationHome,
    required this.organizationAboutUs,
    required this.organizationContactUs,
    required this.organizationUserGuideLine,
  });
}