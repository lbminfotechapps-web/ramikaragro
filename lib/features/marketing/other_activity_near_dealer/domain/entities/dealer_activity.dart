class DealerActivity {
  final String loginUserId;
  final String shopId;
  final String shopName;
  final String outletType;
  final String workDetails;
  final String discussionAbout;
  final String workDone;
  final String output;
  final String kmReading;
  final String manualDistance;
  final String dealerImagePath;
  final String shopBoardImagePath;

  const DealerActivity({
    required this.loginUserId,
    required this.shopId,
    required this.shopName,
    required this.outletType,
    required this.workDetails,
    required this.discussionAbout,
    required this.workDone,
    required this.output,
    required this.kmReading,
    required this.manualDistance,
    required this.dealerImagePath,
    required this.shopBoardImagePath,
  });
}